function TransferHeatmap({ rows, selectedModel, theme }) {
  const targets = DATASETS;
  const sources = [...DATASETS, "pooled"];
  const cells = rows.filter((row) => row.model === selectedModel);
  const values = cells.map((row) => Number(row.mae)).filter(Number.isFinite);
  const min = Math.min(...values, 0);
  const max = Math.max(...values, 1);
  const matrix = new Map(cells.map((row) => [`${row.source_dataset}-${row.target_dataset}`, Number(row.mae)]));

  return (
    <div className="heatmap-wrap">
      <div className="heatmap" role="table" aria-label={`${selectedModel} cross-subset MAE matrix`}>
        <div className="heat-label">TRAIN / TEST</div>
        {targets.map((target) => <div className="heat-label" key={target}>{target}</div>)}
        {sources.map((source) => (
          <div className="heat-row" role="row" key={source}>
            <div className={`source-label ${source === "pooled" ? "pooled-label" : ""}`}>{source}</div>
            {targets.map((target) => {
              const value = matrix.get(`${source}-${target}`);
              const strength = Number.isFinite(value) ? 0.12 + 0.76 * ((value - min) / (max - min || 1)) : 0;
              return (
                <div
                  className="heat-cell"
                  key={target}
                  style={{ backgroundColor: Number.isFinite(value) ? `rgba(199, 91, 72, ${strength})` : theme === "dark" ? "#293532" : "#f0f2f0" }}
                  title={`${source} to ${target}: ${format(value)} cycles MAE`}
                >
                  {format(value)}
                </div>
              );
            })}
          </div>
        ))}
      </div>
      <div className="heat-legend"><span>Lower error</span><i /><span>Higher error</span><small>MAE in cycles</small></div>
    </div>
  );
}

