        <div><span className="eyebrow">POOLED MODEL / {best?.target_dataset ?? "--"}</span><b>{format(best?.mae)} <small>MAE cycles</small></b><span>Best pooled-domain test result in this run: {best?.target_dataset ?? "--"}.</span></div>
